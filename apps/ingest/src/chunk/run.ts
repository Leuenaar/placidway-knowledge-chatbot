import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { DbPageType } from "../pages.js";
import { chunkPage } from "./chunk.js";
import { type Chunk, type PageInput } from "./types.js";
import { bodyWithoutPrefix, verifyPage } from "./verify.js";

// ===== BAGIAN 1: Tipe: satu baris manifest (halaman, jumlah chunk, hash) =====
export interface ManifestEntry {
  pageNo: number;
  file: string;
  sourceUrl: string;
  pageType: DbPageType;
  hash: string;
  meta: { h1: string; modifiedDate?: string };
}

// ===== BAGIAN 2: Tipe: hasil seluruh pemotongan =====
export interface ChunkRun {
  chunks: Chunk[];
  warnings: string[];
  problems: string[];
  perPage: { pageNo: number; chunks: number; minChars: number; maxChars: number; kinds: Record<string, number> }[];
}

// ===== BAGIAN 3: Memotong semua halaman, memeriksa, dan menulis berkas =====
/** Read the cleaned pages, chunk them, check the gates, and write data/chunks/. */
export function chunkDirectory(cleanedDir: string, outDir: string): ChunkRun {
  const manifest = JSON.parse(readFileSync(join(cleanedDir, "manifest.json"), "utf8")) as ManifestEntry[];
  const run: ChunkRun = { chunks: [], warnings: [], problems: [], perPage: [] };

  for (const m of manifest) {
    const page: PageInput = {
      pageNo: m.pageNo,
      sourceUrl: m.sourceUrl,
      pageType: m.pageType,
      text: readFileSync(join(cleanedDir, m.file), "utf8"),
      h1: m.meta.h1,
      ...(m.meta.modifiedDate ? { modifiedDate: m.meta.modifiedDate } : {}),
    };
    const res = chunkPage(page);
    run.warnings.push(...res.warnings.map((w) => `page ${m.pageNo}: ${w}`));
    run.problems.push(...verifyPage(page, res.chunks).map((p) => `page ${m.pageNo}: ${p}`));
    run.chunks.push(...res.chunks);
    const sizes = res.chunks.map((c) => c.text.length);
    const kinds: Record<string, number> = {};
    for (const c of res.chunks) kinds[c.kind] = (kinds[c.kind] ?? 0) + 1;
    run.perPage.push({ pageNo: m.pageNo, chunks: res.chunks.length, minChars: Math.min(...sizes), maxChars: Math.max(...sizes), kinds });
  }

  const ids = new Set<string>();
  for (const c of run.chunks) {
    if (ids.has(c.id)) run.problems.push(`${c.id}: duplicate id across pages`);
    ids.add(c.id);
  }

  mkdirSync(outDir, { recursive: true });
  writeFileSync(join(outDir, "chunks.json"), JSON.stringify(run.chunks, null, 2) + "\n", "utf8");
  writeFileSync(join(outDir, "chunk-report.md"), renderChunkReport(run), "utf8");
  return run;
}

// ===== BAGIAN 4: Membuat laporan pemotongan yang mudah dibaca =====
function renderChunkReport(run: ChunkRun): string {
  const out: string[] = ["# Chunk report", "", `${run.chunks.length} chunks. Generated by \`npm run ingest:chunk\`.`, ""];
  out.push("## Per page", "", "| Page | Chunks | Smallest | Largest | Kinds |", "| ---: | ---: | ---: | ---: | --- |");
  for (const p of run.perPage) {
    const kinds = Object.entries(p.kinds)
      .map(([k, v]) => `${k} ${v}`)
      .join(", ");
    out.push(`| ${p.pageNo} | ${p.chunks} | ${p.minChars} | ${p.maxChars} | ${kinds} |`);
  }
  out.push("", "## Problems", "");
  if (run.problems.length === 0) out.push("- none");
  for (const p of run.problems) out.push(`- ${p}`);
  out.push("", "## Warnings", "");
  if (run.warnings.length === 0) out.push("- none");
  for (const w of run.warnings) out.push(`- ${w}`);
  out.push("", "## All chunks", "", "| Id | Kind | Chars | Section | Starts with |", "| --- | --- | ---: | --- | --- |");
  for (const c of run.chunks) {
    const start = bodyWithoutPrefix(c).replace(/\s+/g, " ").slice(0, 70).replace(/\|/g, "/");
    out.push(`| ${c.id} | ${c.kind} | ${c.text.length} | ${c.section.replace(/\|/g, "/").slice(0, 90)} | ${start} |`);
  }
  out.push("");
  return out.join("\n");
}
