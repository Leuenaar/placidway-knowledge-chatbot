import type { CleanResult } from "./types.js";

// ===== BAGIAN 1: Membuat laporan markdown pembersihan =====
/** Human-readable cleaning report (R10): what was removed, and every removed $ amount. */
export function renderReportMd(results: CleanResult[]): string {
  const out: string[] = [];
  out.push("# Cleaning report", "");
  out.push(
    "Generated by `npm run ingest:clean`. Read the last two sections of each page: they list the removed text that carried a $ amount and any warning.",
    "",
  );

  out.push("## Summary", "");
  out.push("| Page | Type | Cleaned chars | Hash (first 12) | $ amounts kept / dropped | R10 |");
  out.push("| --- | --- | ---: | --- | --- | --- |");
  for (const r of results) {
    const a = r.report.amounts;
    out.push(
      `| ${r.pageNo} | ${r.pageType} | ${r.text.length} | ${r.hash.slice(0, 12)} | ${a.cleaned.length} / ${a.dropped.length} | ${a.ok ? "OK" : "PROBLEM"} |`,
    );
  }
  out.push("");

  for (const r of results) {
    out.push(`## Page ${r.pageNo}: ${r.meta.h1}`, "");
    out.push(`- Source: ${r.sourceUrl}`);
    out.push(`- Kept raw lines ${r.report.keptFromLine} to ${r.report.keptToLine}; ${r.report.urlsRemoved} links removed`);
    const meta = Object.entries(r.meta)
      .filter(([k]) => k !== "h1")
      .map(([k, v]) => `${k}=${v}`)
      .join("; ");
    out.push(`- Metadata kept: ${meta || "none"}`);
    out.push("", "Lines removed or converted per rule:", "");
    const rules = Object.entries(r.report.ruleCounts).sort(([a], [b]) => a.localeCompare(b));
    out.push("| Rule | Count |", "| --- | ---: |");
    for (const [k, v] of rules) out.push(`| ${k} | ${v} |`);

    const withAmounts = r.report.dropped.filter((d) => d.amounts.length > 0);
    out.push("", "Removed text that contains a $ amount (human review):", "");
    if (withAmounts.length === 0) out.push("- none");
    for (const d of withAmounts) out.push(`- [${d.rule}] raw line ${d.line}: ${d.amounts.join(", ")} in "${d.preview}"`);

    const review = r.report.dropped.filter((d) => /^(R3-widget|R3-readmore|X1-related|R7-toc|R5-unnamed-row|X3-video-list-duplicate)$/.test(d.rule));
    out.push("", "Larger blocks removed (spot check):", "");
    if (review.length === 0) out.push("- none");
    for (const d of review) out.push(`- [${d.rule}] raw line ${d.line}, ${d.count} lines: "${d.preview}"`);

    out.push("", "Warnings:", "");
    if (r.report.warnings.length === 0) out.push("- none");
    for (const w of r.report.warnings) out.push(`- ${w}`);
    out.push("");
  }
  return out.join("\n");
}
